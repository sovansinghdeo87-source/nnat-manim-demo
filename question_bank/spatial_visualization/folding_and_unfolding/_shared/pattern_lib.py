"""
Shared content engine for Spatial Visualization -> Folding and Unfolding.

The classic paper-folding puzzle: a square grid of paper is folded
along one or more lines, a hole is punched through the folded
(stacked) layers, and the paper is unfolded. The question shows the
grid with its fold line(s) marked and a dot at the punch location (the
standard print-test convention); the answer choices show candidate
unfolded hole patterns.

This is modeled RIGOROUSLY, not just visually: each fold is a
reflection of grid coordinates (vertical: c -> n-1-c, horizontal:
r -> n-1-r, diagonal: (r,c) -> (c,r)). The actual unfolded hole set is
the closure of the punch point under the group generated by the fold
reflections used -- exactly what happens physically (one fold doubles
the hole count via one reflection; two perpendicular folds quadruple
it via the Klein four-group {identity, vertical, horizontal, both}).
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from typing import Optional

import numpy as np
from manim import *
from manim_voiceover import VoiceoverScene
from manim_voiceover.services.azure import AzureService

INK = "#1A1A2E"
ACCENT = "#3B82F6"
FRONT_COLOR = "#F59E0B"
CORRECT = "#22C55E"
BG = WHITE

TITLE_SIZE = 40
QUESTION_SIZE = 28
CHOICE_LETTER_SIZE = 24
ANSWER_SIZE = 40

AZURE_VOICE = "en-US-JennyNeural"
TITLE_TEXT = "Spatial Visualization"
QUESTION_TEXT = "The paper is folded (dashed line) and a hole is punched (dot). Unfolded, which pattern of holes results?"

GRADE_LABELS = ["K", "1", "2", "3", "4"]

ATTRIBUTES = ["fold_vertical", "fold_horizontal", "fold_both", "fold_both_large", "fold_diagonal"]
GRID_SIZE_BY_ATTR = {
    "fold_vertical": 4, "fold_horizontal": 4, "fold_both": 4,
    "fold_both_large": 6, "fold_diagonal": 4,
}
FOLD_AXES_BY_ATTR = {
    "fold_vertical": ("vertical",), "fold_horizontal": ("horizontal",),
    "fold_both": ("vertical", "horizontal"), "fold_both_large": ("vertical", "horizontal"),
    "fold_diagonal": ("diagonal",),
}
DIFFICULTY_BY_GRADE = {0: 1, 1: 2, 2: 3, 3: 4, 4: 5}


def _refl(axis: str, r: int, c: int, n: int) -> tuple[int, int]:
    if axis == "vertical":
        return (r, n - 1 - c)
    if axis == "horizontal":
        return (n - 1 - r, c)
    if axis == "diagonal":
        return (c, r)
    raise ValueError(axis)


def orbit(punch: tuple[int, int], axes: tuple[str, ...], n: int) -> frozenset[tuple[int, int]]:
    pts = {punch}
    changed = True
    while changed:
        changed = False
        for axis in axes:
            new_pts = {_refl(axis, r, c, n) for (r, c) in pts}
            if not new_pts <= pts:
                pts |= new_pts
                changed = True
    return frozenset(pts)


@dataclass(frozen=True)
class PatternSpec:
    grade_rank: int
    question_number: int
    attribute: str
    variation_index: int = 0
    palette_offset: int = 0

    @property
    def grade_label(self) -> str:
        return GRADE_LABELS[self.grade_rank]

    @property
    def difficulty(self) -> int:
        return DIFFICULTY_BY_GRADE[self.grade_rank]

    @property
    def grid_size(self) -> int:
        return GRID_SIZE_BY_ATTR[self.attribute]

    @property
    def fold_axes(self) -> tuple[str, ...]:
        return FOLD_AXES_BY_ATTR[self.attribute]

    @property
    def punch_cell(self) -> tuple[int, int]:
        n = self.grid_size
        half = n // 2
        off = self.palette_offset
        if self.attribute == "fold_diagonal":
            pairs = [(r, c) for r in range(n) for c in range(n) if r < c]
            return pairs[off % len(pairs)]
        r = off % half
        c = (off + 1 + off // half) % half
        return (r, c)

    @property
    def question_id(self) -> str:
        base = f"sv_fold_{self.grade_label}_q{self.question_number:02d}"
        if self.variation_index:
            return f"{base}_v{self.variation_index}"
        return base


def correct_holes_for(spec: PatternSpec) -> frozenset[tuple[int, int]]:
    return orbit(spec.punch_cell, spec.fold_axes, spec.grid_size)


ALL_AXES = ("vertical", "horizontal", "diagonal")


def distractor_hole_sets_for(spec: PatternSpec, correct: frozenset) -> list[frozenset]:
    n = spec.grid_size
    axes = spec.fold_axes
    r0, c0 = spec.punch_cell

    if len(axes) > 1:
        missing_fold = orbit(spec.punch_cell, axes[:-1], n)
    else:
        extra_axis = next(a for a in ALL_AXES if a not in axes and a != "diagonal")
        missing_fold = orbit(spec.punch_cell, axes + (extra_axis,), n)

    other_axis = next(a for a in ALL_AXES if a not in axes)
    wrong_axis = orbit(spec.punch_cell, (other_axis,), n)

    shifted_punch = ((r0 + 1) % n, c0)
    shifted = orbit(shifted_punch, axes, n)

    far_punch = ((r0 + n // 2) % n, (c0 + n // 2) % n)
    unrelated = orbit(far_punch, axes, n)

    candidates = [missing_fold, wrong_axis, shifted, unrelated]
    used = {correct}
    distractors: list[frozenset] = []
    for cand in candidates:
        if cand not in used and cand not in distractors:
            distractors.append(cand)
        if len(distractors) == 4:
            break

    dr = 0
    while len(distractors) < 4 and dr < n:
        cand = orbit(((r0 + dr) % n, (c0 + dr + 1) % n), axes, n)
        dr += 1
        if cand not in used and cand not in distractors:
            distractors.append(cand)

    if len(distractors) < 4:
        raise RuntimeError(f"Could not generate 4 unique distractors for {spec.question_id}")
    return distractors[:4]


def choice_hole_sets_for(spec: PatternSpec, correct: frozenset) -> tuple[list[frozenset], str]:
    distractors = distractor_hole_sets_for(spec, correct)
    choices = distractors + [correct]
    rng = random.Random(spec.question_id)
    rng.shuffle(choices)
    correct_letter = "ABCDE"[choices.index(correct)]
    return choices, correct_letter


def build_grid_square(n: int, scale: float = 1.0, color: str = INK):
    side = 1.6 * scale
    cell_size = side / n
    square = Square(side_length=side, color=color, stroke_width=3)
    lines = VGroup()
    for i in range(1, n):
        x = -side / 2 + i * cell_size
        lines.add(Line([x, -side / 2, 0], [x, side / 2, 0], color=color, stroke_width=1.5, stroke_opacity=0.5))
        y = -side / 2 + i * cell_size
        lines.add(Line([-side / 2, y, 0], [side / 2, y, 0], color=color, stroke_width=1.5, stroke_opacity=0.5))
    return VGroup(square, lines), cell_size, side


def _cell_center(r: int, c: int, cell_size: float, side: float) -> np.ndarray:
    x = -side / 2 + cell_size * (c + 0.5)
    y = side / 2 - cell_size * (r + 0.5)
    return np.array([x, y, 0])


def build_fold_diagram(spec: PatternSpec, scale: float = 1.0):
    grid, cell_size, side = build_grid_square(spec.grid_size, scale)
    fold_lines = VGroup()
    for axis in spec.fold_axes:
        if axis == "vertical":
            fold_lines.add(DashedLine([0, -side / 2, 0], [0, side / 2, 0], color=ACCENT, stroke_width=4))
        elif axis == "horizontal":
            fold_lines.add(DashedLine([-side / 2, 0, 0], [side / 2, 0, 0], color=ACCENT, stroke_width=4))
        elif axis == "diagonal":
            fold_lines.add(DashedLine([-side / 2, -side / 2, 0], [side / 2, side / 2, 0], color=ACCENT, stroke_width=4))
    punch = Dot(_cell_center(*spec.punch_cell, cell_size, side), radius=0.09 * scale, color=FRONT_COLOR)
    return VGroup(grid, fold_lines, punch)


def build_result_grid(holes: frozenset, n: int, scale: float = 1.0):
    grid, cell_size, side = build_grid_square(n, scale)
    dots = VGroup(*[Dot(_cell_center(r, c, cell_size, side), radius=0.075 * scale, color=INK) for (r, c) in holes])
    return VGroup(grid, dots)


def make_title():
    return Text(TITLE_TEXT, font_size=TITLE_SIZE, color=INK, weight=BOLD).to_edge(UP, buff=0.5)


def make_question():
    return Text(QUESTION_TEXT, font_size=QUESTION_SIZE - 4, color=INK)


def build_choice_row(spec: PatternSpec, choices: list[frozenset], labels=("A", "B", "C", "D", "E"), buff=0.6):
    group = VGroup(*[build_result_grid(c, spec.grid_size, 0.7) for c in choices]).arrange(RIGHT, buff=buff)
    full = VGroup()
    for letter, mobj in zip(labels, group):
        letter_text = Text(letter, font_size=CHOICE_LETTER_SIZE, color=INK, weight=BOLD)
        letter_text.next_to(mobj, UP, buff=0.3)
        full.add(VGroup(letter_text, mobj))
    full.move_to(ORIGIN)
    _max_w = min(12, config.frame_width - 1.0)
    if full.width > _max_w:
        full.scale(_max_w / full.width)
    return full


def surround(mobj, color=CORRECT):
    return SurroundingRectangle(mobj, color=color, buff=0.2, stroke_width=6, corner_radius=0.1)


_AXIS_WORD = {"vertical": "left-right", "horizontal": "top-bottom", "diagonal": "diagonal"}


def narration_lines(spec: PatternSpec, correct_letter: str) -> dict:
    fold_desc = " and ".join(_AXIS_WORD[a] for a in spec.fold_axes)
    return {
        "intro": QUESTION_TEXT,
        "fold": f"It's folded {fold_desc}, and a hole is punched.",
        "choices": "Here are the five answer choices, A through E.",
        "reveal": f"The correct answer is {correct_letter}.",
        "explain": "Every fold doubles the holes, mirrored across that line.",
        "final": f"So the answer is {correct_letter}.",
    }


def _spread_group_vertically(group, margin: float = 0.6, min_gap: float = 0.5,
                               max_gap: float = 1.6) -> None:
    """Re-stack a VGroup's top-level children (title, question, content,
    choices, ...) top-to-bottom with equal gaps sized to use the full 9:16
    frame, instead of trusting each child's original absolute placement --
    some of which was tuned for a shorter 16:9 frame and left huge or
    lopsided dead space when rendered tall. Children keep their own size
    and internal layout; only the vertical gap between them changes."""
    children = sorted(group.submobjects, key=lambda c: -c.get_center()[1])
    if len(children) < 2:
        return
    content_h = sum(c.height for c in children)
    available = config.frame_height - 2 * margin
    n_gaps = len(children) - 1
    gap = (available - content_h) / n_gaps if n_gaps else 0.0
    gap = max(min_gap, min(max_gap, gap))
    cursor = children[0].get_top()[1]
    for c in children:
        c.shift(UP * (cursor - c.get_top()[1]))
        cursor = c.get_bottom()[1] - gap


def render_question_image(scene: Scene, spec: PatternSpec) -> None:
    scene.camera.background_color = BG
    title = make_title()
    question = make_question().next_to(title, DOWN, buff=0.35)
    _max_w = min(11.5, config.frame_width - 1.0)
    if question.width > _max_w:
        question.scale(_max_w / question.width)

    diagram = build_fold_diagram(spec, scale=1.1)
    diagram.next_to(question, DOWN, buff=0.5)

    correct = correct_holes_for(spec)
    choices, _ = choice_hole_sets_for(spec, correct)
    choice_group = build_choice_row(spec, choices)
    choice_group.next_to(diagram, DOWN, buff=0.7)

    _group = VGroup(title, question, diagram, choice_group)
    _spread_group_vertically(_group)
    _group.move_to(ORIGIN)
    scene.add(_group)


class FoldingAndUnfoldingVideoScene(VoiceoverScene):
    SPEC: Optional[PatternSpec] = None

    def construct(self):
        spec = self.SPEC
        self.camera.background_color = BG
        self.set_speech_service(AzureService(voice=AZURE_VOICE))

        title = make_title()
        question = make_question().next_to(title, DOWN, buff=0.35)
        _max_w = min(11.5, config.frame_width - 1.0)
        if question.width > _max_w:
            question.scale(_max_w / question.width)

        with self.voiceover(text=narration_lines(spec, "")["intro"]) as tracker:
            self.play(Write(title), run_time=0.8)
            self.play(FadeIn(question, shift=UP * 0.2), run_time=0.7)
            self.wait(tracker.get_remaining_duration())

        diagram = build_fold_diagram(spec, scale=1.1)
        diagram.move_to(ORIGIN).shift(UP * 0.7)

        lines = narration_lines(spec, "")
        with self.voiceover(text=lines["fold"]) as tracker:
            self.play(FadeIn(diagram, shift=UP * 0.2), run_time=1.0)
            self.wait(tracker.get_remaining_duration())

        correct = correct_holes_for(spec)
        choices, correct_letter = choice_hole_sets_for(spec, correct)
        lines = narration_lines(spec, correct_letter)
        choice_group = build_choice_row(spec, choices)
        choice_group.next_to(diagram, DOWN, buff=0.7)

        with self.voiceover(text=lines["choices"]) as tracker:
            self.play(FadeIn(choice_group, shift=UP * 0.3), run_time=0.9)
            self.wait(tracker.get_remaining_duration())

        correct_index = "ABCDE".index(correct_letter)
        choice_correct = choice_group[correct_index]
        box = surround(choice_correct)
        with self.voiceover(text=lines["reveal"]) as tracker:
            self.play(Create(box), run_time=0.6)
            self.play(Indicate(choice_correct, color=CORRECT, scale_factor=1.15), run_time=0.6)
            self.wait(tracker.get_remaining_duration())

        with self.voiceover(text=lines["explain"]) as tracker:
            self.play(FadeOut(choice_group), FadeOut(box), run_time=0.4)
            self.wait(tracker.get_remaining_duration())

        answer_text = Text(f"Answer: {correct_letter}", font_size=ANSWER_SIZE, color=CORRECT, weight=BOLD)
        answer_text.next_to(diagram, DOWN, buff=0.6)
        with self.voiceover(text=lines["final"]) as tracker:
            self.play(FadeIn(answer_text, scale=0.8), run_time=0.7)
            self.wait(tracker.get_remaining_duration())

        self.wait(0.4)
        self.play(
            FadeOut(VGroup(title, question, diagram, answer_text)),
            run_time=0.8,
        )


def metadata_for(spec: PatternSpec) -> dict:
    correct = correct_holes_for(spec)
    choices, correct_letter = choice_hole_sets_for(spec, correct)
    lines = narration_lines(spec, correct_letter)
    return {
        "question_id": spec.question_id,
        "category": "spatial_visualization",
        "skill": "folding_and_unfolding",
        "subskill_attribute": spec.attribute,
        "difficulty": spec.difficulty,
        "grid_size": spec.grid_size,
        "fold_axes": list(spec.fold_axes),
        "punch_cell": list(spec.punch_cell),
        "correct_holes": sorted(list(correct)),
        "grade_label": spec.grade_label,
        "grade_rank": spec.grade_rank,
        "minimum_grade": spec.grade_rank,
        "maximum_grade": spec.grade_rank,
        "variation_of": (f"sv_fold_{spec.grade_label}_q{spec.question_number:02d}"
                          if spec.variation_index else None),
        "variation_index": spec.variation_index,
        "title": TITLE_TEXT,
        "question_text": QUESTION_TEXT,
        "format": "multiple_choice_5",
        "correct_answer": correct_letter,
        "explanation_script": [
            lines["intro"], lines["fold"], lines["choices"],
            lines["reveal"], lines["explain"], lines["final"],
        ],
    }
